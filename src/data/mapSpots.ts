export function resolveSpotId(idOrAlias: string): string {
  const cleaned = idOrAlias.trim();
  if (SPOTS[cleaned]) return cleaned;
  const target = SPOT_ALIASES[cleaned];
  if (target && SPOTS[target]) return target;
  return cleaned;
}

export function resolveSpot(idOrAlias: string): SpotData | undefined {
  const canonicalId = resolveSpotId(idOrAlias);
  return SPOTS[canonicalId];
}

